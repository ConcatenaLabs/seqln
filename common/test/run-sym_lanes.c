/* A symmetric channel that holds several assets settles each in its own:
 * the settlement's outputs name their asset, SETTLE hashes it, and a state
 * encodes it (common/sym_state.h).  Checked against vectors from the
 * builders that were spent on a Sequentia chain with every negative case
 * forced into a block (sym_lanes_vectors.h); and a state that names no
 * asset encodes exactly as before. */
