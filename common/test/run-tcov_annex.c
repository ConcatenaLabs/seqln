/* A BIP341 annex on a taproot-covenant spend: consensus takes it and relay
 * policy does not, so a block producer can mine one.  The witnesses in
 * tcov_annex_vectors.h were each mined that way on a Sequentia chain: the
 * peer's offered-SUCCESS claim, whose signature commits to the annex, and a
 * keyless REVOKE claim with an annex nobody signed.  onchaind reads every
 * taproot witness through tap_witness_items(): the SUCCESS claim's secret
 * is item 1 of four (tcov_extract_preimage), and a spend of its own is
 * recognised with an annex appended (onchain_witness_element_matches). */
