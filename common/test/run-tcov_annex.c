static struct wally_tx_witness_stack *stack_of(const char **hexes, size_t n)
{
	struct wally_tx_witness_stack *st;

	tal_wally_start();
	assert(wally_tx_witness_stack_init_alloc(n, &st) == WALLY_OK);
	for (size_t i = 0; i < n; i++) {
		u8 *b = tal_hexdata(tmpctx, hexes[i], strlen(hexes[i]));
		assert(b);
		assert(wally_tx_witness_stack_add(st, b, tal_bytelen(b))
		       == WALLY_OK);
	}
	tal_wally_end(tmpctx);
	return st;
}

int main(int argc, char *argv[])
{
	struct wally_tx_witness_stack *st;
	const u8 *secret;
	u8 *want;
	const char *one[] = { "50aa" };
	const char *keypath_annex[] = { "11", "50" };
	const char *empty_last[] = { "11", "22", "" };
	const char *other_last[] = { "11", "22", "51" };

	common_setup(argv[0]);

	/* The mined SUCCESS claim: four items and an annex.  The secret it
	 * reveals is the payment's preimage. */
	assert(ARRAY_SIZE(V_SUCCESS_ANNEXED) == 5);
	st = stack_of(V_SUCCESS_ANNEXED, ARRAY_SIZE(V_SUCCESS_ANNEXED));
	assert(st->num_items == 5);
	assert(tap_witness_items(st) == 4);
	secret = st->items[1].witness;
	assert(st->items[1].witness_len == 32);
	want = tal_hexdata(tmpctx, V_SUCCESS_PREIMAGE, strlen(V_SUCCESS_PREIMAGE));
	assert(memeq(secret, 32, want, tal_bytelen(want)));

	/* The same claim without its annex reads the same. */
	st = stack_of(V_SUCCESS_ANNEXED, 4);
	assert(tap_witness_items(st) == 4);
	assert(memeq(st->items[1].witness, 32, want, tal_bytelen(want)));

	/* Five items whose last is not an annex: five items. */
	{
		const char *five[5];
		for (size_t i = 0; i < 4; i++)
			five[i] = V_SUCCESS_ANNEXED[i];
		five[4] = "51";
		st = stack_of(five, 5);
		assert(tap_witness_items(st) == 5);
		}

	/* The mined REVOKE claim: secret, leaf, control block, annex. */
	assert(ARRAY_SIZE(V_REVOKE_ANNEXED) == 4);
	st = stack_of(V_REVOKE_ANNEXED, ARRAY_SIZE(V_REVOKE_ANNEXED));
	assert(tap_witness_items(st) == 3);

	/* BIP341's rule at its edges: one item is never an annex; a key path
	 * spend can carry one; the last item must start with 0x50. */
	st = stack_of(one, ARRAY_SIZE(one));
	assert(tap_witness_items(st) == 1);
	st = stack_of(keypath_annex, ARRAY_SIZE(keypath_annex));
	assert(tap_witness_items(st) == 1);
	st = stack_of(empty_last, ARRAY_SIZE(empty_last));
	assert(tap_witness_items(st) == 3);
	st = stack_of(other_last, ARRAY_SIZE(other_last));
	assert(tap_witness_items(st) == 3);
	assert(tap_witness_items(NULL) == 0);

	common_shutdown();
	return 0;
}
