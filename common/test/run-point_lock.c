static u8 *unhex(const tal_t *ctx, const char *h)
{
	u8 *b = tal_hexdata(ctx, h, strlen(h));
	assert(b);
	return b;
}

static void scalar_of(const char *h, struct preimage *p)
{
	assert(hex_decode(h, strlen(h), p->r, sizeof(p->r)));
}

static void secret_of(const char *h, struct secret *s)
{
	assert(hex_decode(h, strlen(h), s->data, sizeof(s->data)));
}

static void point_of(const char *h, struct pubkey *pk)
{
	assert(pubkey_from_hexstr(h, strlen(h), pk));
}

static void pubkey_of(const char *secret_hex, struct pubkey *pk)
{
	struct privkey p;
	secret_of(secret_hex, &p.secret);
	assert(pubkey_from_privkey(&p, pk));
}

static void check(const char *what, const u8 *got, const char *want_hex)
{
	u8 *want = unhex(tmpctx, want_hex);
	if (!memeq(got, tal_bytelen(got), want, tal_bytelen(want))) {
		fprintf(stderr, "%s:\n got  %s\n want %s\n", what,
			tal_hex(tmpctx, got), want_hex);
		abort();
	}
}

int main(int argc, char *argv[])
{
	struct preimage p, s0, s1, got, bad;
	struct secret r, d, negd;
	struct pubkey T, L0, L1, P;
	struct sha256 x, payment_hash;
	struct basepoints self, other;
	struct pubkey pcp;
	struct keyset ks;
	struct tap_tree2 off, rcv;
	struct ripemd160 rmd;
	u8 *asset_tag;

	common_setup(argv[0]);
	chainparams = chainparams_for_network("sequentia-regtest");

	scalar_of(PL_P, &p);
	secret_of(PL_R, &r);
	secret_of(PL_D, &d);
	scalar_of(PL_S0, &s0);
	scalar_of(PL_S1, &s1);
	point_of(PL_T, &T);
	point_of(PL_L0, &L0);
	point_of(PL_L1, &L1);

	/* The invoice's point is the preimage's. */
	assert(point_lock_point_of(&p, &P) && pubkey_eq(&P, &T));
	/* The payee opens L1 = T + r*G with p + r. */
	assert(point_lock_scalar_add(&p, &r, &got) && preimage_eq(&got, &s1));
	assert(point_lock_opens(&L1, &s1));
	/* The forwarder: told d, it offers L0 + d*G = L1, and opens L0 with
	 * s1 - d (lightningd adds -d). */
	assert(point_lock_tweak(&L0, &d, &P) && pubkey_eq(&P, &L1));
	assert(point_lock_scalar_negate(&d, &negd));
	assert(point_lock_scalar_add(&s1, &negd, &got) && preimage_eq(&got, &s0));
	assert(point_lock_scalar_sub(&s1, &d, &got) && preimage_eq(&got, &s0));
	assert(point_lock_opens(&L0, &s0));
	/* No hop's scalar opens another hop's point, nor does the invoice
	 * preimage open either. */
	assert(!point_lock_opens(&L0, &s1));
	assert(!point_lock_opens(&L1, &s0));
	assert(!point_lock_opens(&L0, &p) && !point_lock_opens(&L1, &p));
	/* The negated scalar opens -L0, not L0: the parity counts. */
	{
		struct secret s0s, neg;
		memcpy(s0s.data, s0.r, 32);
		assert(point_lock_scalar_negate(&s0s, &neg));
		memcpy(bad.r, neg.data, 32);
		assert(!point_lock_opens(&L0, &bad));
	}
	/* Zero and the group order are no scalars. */
	memset(bad.r, 0, 32);
	assert(!point_lock_scalar_valid(&bad));
	assert(!point_lock_opens(&L0, &bad));
	assert(hex_decode("fffffffffffffffffffffffffffffffebaaedce6af48a03bbfd25e8cd0364141",
			  64, bad.r, 32));
	assert(!point_lock_scalar_valid(&bad));
	/* An HTLC locked to L0 carries L0's x as its payment_hash. */
	point_lock_payment_hash(&L0, &x);
	check("payment hash of L0", tal_dup_arr(tmpctx, u8, x.u.u8, 32, 0),
	      tal_hexstr(tmpctx, unhex(tmpctx, PL_L0) + 1, 32));

	/* The trees of an HTLC locked to L0, with tcov_vectors.h's keys. */
	pubkey_of(V_SELF_PAYMENT_SECRET, &self.payment);
	pubkey_of(V_SELF_HTLC_SECRET, &self.htlc);
	pubkey_of(V_SELF_DELAYED_SECRET, &self.delayed_payment);
	pubkey_of(V_OTHER_REVOCATION_SECRET, &other.revocation);
	pubkey_of(V_OTHER_PAYMENT_SECRET, &other.payment);
	pubkey_of(V_OTHER_HTLC_SECRET, &other.htlc);
	self.revocation = self.payment;
	other.delayed_payment = other.payment;
	assert(pubkey_from_hexstr(V_PER_COMMITMENT_POINT,
				  strlen(V_PER_COMMITMENT_POINT), &pcp));
	assert(derive_keyset(&pcp, &self, &other, true, &ks));
	asset_tag = unhex(tmpctx, V_ASSET_TAG);
	/* The hash lock's ripemd is ignored when a lock point is given. */
	assert(hex_decode(V_PAYMENT_HASH, strlen(V_PAYMENT_HASH),
			  payment_hash.u.u8, sizeof(payment_hash.u.u8)));
	ripemd160(&rmd, payment_hash.u.u8, sizeof(payment_hash.u.u8));

	tcov_offered_htlc_tree(tmpctx, &ks, &pcp, V_DELAY, asset_tag, &rmd,
			       &L0, V_CLTV, amount_sat(V_X), &off);
	check("offered success leaf (point)", off.leaf[TCOV_LEAF_OFFERED_SUCCESS],
	      PL_OFFERED_SUCCESS_LEAF);
	check("offered timeout leaf (as hash-locked)",
	      off.leaf[TCOV_LEAF_OFFERED_TIMEOUT], V_OFFERED_TIMEOUT_LEAF);
	check("offered spk (point)", tap_tree2_scriptpubkey(tmpctx, &off), PL_OFFERED_SPK);
	check("offered cb success (point)",
	      tap_tree2_control_block(tmpctx, &off, TCOV_LEAF_OFFERED_SUCCESS),
	      PL_OFFERED_CB_SUCCESS);
	tcov_received_htlc_tree(tmpctx, &ks, &pcp, V_DELAY, asset_tag, &rmd,
				&L0, V_CLTV, amount_sat(V_X), &rcv);
	check("received success leaf (point)", rcv.leaf[TCOV_LEAF_RECEIVED_SUCCESS],
	      PL_RECEIVED_SUCCESS_LEAF);
	check("received spk (point)", tap_tree2_scriptpubkey(tmpctx, &rcv), PL_RECEIVED_SPK);
	/* 70 bytes of point lock, against the hash lock's 27. */
	assert(tal_bytelen(off.leaf[TCOV_LEAF_OFFERED_SUCCESS]) == 70 + 34);

	/* Without a lock point the trees are the hash-locked ones. */
	tcov_offered_htlc_tree(tmpctx, &ks, &pcp, V_DELAY, asset_tag, &rmd,
			       NULL, V_CLTV, amount_sat(V_X), &off);
	check("offered spk (hash)", tap_tree2_scriptpubkey(tmpctx, &off), V_OFFERED_SPK);

	common_shutdown();
	return 0;
}
