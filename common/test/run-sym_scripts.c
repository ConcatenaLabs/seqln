/* The symmetric channel type's scripts, trees, messages and kickoff, against
 * vectors from the Sequentia node's test framework (sym_vectors.h), whose
 * builders were proved on a Sequentia chain with every negative case forced
 * into a block; and the settlement's rules on trimming and rounding. */
