static u8 *unhex(const tal_t *ctx, const char *h)
{
	u8 *b = tal_hexdata(ctx, h, strlen(h));
	assert(b);
	return b;
}

static void pubkey_of(const char *secret_hex, struct pubkey *pk)
{
	struct privkey p;
	assert(hex_decode(secret_hex, strlen(secret_hex), p.secret.data, 32));
	assert(pubkey_from_privkey(&p, pk));
}

static void check(const char *what, const u8 *got, const char *want_hex)
{
	u8 *want = unhex(tmpctx, want_hex);
	if (!memeq(got, tal_bytelen(got), want, tal_bytelen(want))) {
		fprintf(stderr, "%s:\n got  %s\n want %s\n", what,
			tal_hex(tmpctx, got), want_hex);
		abort();
	}
}

static u8 *bytes(const void *p, size_t n)
{
	return tal_dup_arr(tmpctx, u8, p, n, 0);
}

int main(int argc, char *argv[])
{
	struct basepoints self, other;
	struct pubkey pcp, provider_funding, provider_payment, holder_payment, ck;
	struct keyset ks;
	struct channel_id cid;
	struct credit_params cp;
	struct tap_tree2 tl, tr;
	struct sha256 h;
	u8 sig[64], der[PUBKEY_CMPR_LEN];

	common_setup(argv[0]);
	chainparams = chainparams_for_network("sequentia-regtest");

	pubkey_of(V_SELF_PAYMENT_SECRET, &self.payment);
	pubkey_of(V_SELF_HTLC_SECRET, &self.htlc);
	pubkey_of(V_SELF_DELAYED_SECRET, &self.delayed_payment);
	pubkey_of(V_OTHER_REVOCATION_SECRET, &other.revocation);
	pubkey_of(V_OTHER_PAYMENT_SECRET, &other.payment);
	pubkey_of(V_OTHER_HTLC_SECRET, &other.htlc);
	self.revocation = self.payment;
	other.delayed_payment = other.payment;
	assert(pubkey_from_hexstr(V_PER_COMMITMENT_POINT,
				  strlen(V_PER_COMMITMENT_POINT), &pcp));
	assert(derive_keyset(&pcp, &self, &other, true, &ks));

	pubkey_of(CV_PROVIDER_FUNDING_SECRET, &provider_funding);
	pubkey_of(CV_PROVIDER_PAYMENT_SECRET, &provider_payment);
	holder_payment = other.payment;
	assert(hex_decode(CV_CHANNEL_ID, strlen(CV_CHANNEL_ID), cid.id, 32));

	/* Dtag, Pc, U */
	assert(credit_params_init(tmpctx, &cid, &provider_funding,
				  &holder_payment, &cp));
	check("dtag", bytes(cp.dtag.u.u8, 32), CV_DTAG);
	assert(credit_key(&provider_funding, &ck));
	pubkey_to_der(der, &ck);
	check("credit key", bytes(der, sizeof(der)), CV_CREDIT_KEY);
	check("holder spk", cp.holder_spk, CV_HOLDER_SPK);
	/* U is what the provider's REVOKE leaf pays too: the holder's
	 * static payment script. */
	check("revoke dest is U", tcov_revoke_dest(tmpctx, &ks), CV_HOLDER_SPK);

	/* The CLAIM leaf, and the trees it sits in. */
	check("claim leaf", credit_leaf_claim(tmpctx, &cp.dtag, &cp.credit_key,
					      amount_sat(CV_V0), cp.holder_spk),
	      CV_CLAIM_LEAF);
	assert(tal_bytelen(credit_leaf_claim(tmpctx, &cp.dtag, &cp.credit_key,
					     amount_sat(CV_V0), cp.holder_spk))
	       == 172);
	credit_to_local_tree(tmpctx, &ks, &pcp, CV_DELAY, &cp, amount_sat(CV_V0), &tl);
	check("to_local spk", tap_tree2_scriptpubkey(tmpctx, &tl), CV_TO_LOCAL_SPK);
	check("to_local root", bytes(tl.merkle_root.u.u8, 32), CV_TO_LOCAL_ROOT);
	check("to_local cb claim",
	      tap_tree2_control_block(tmpctx, &tl, CREDIT_LEAF_CLAIM), CV_TO_LOCAL_CB_CLAIM);
	check("to_local cb delay",
	      tap_tree2_control_block(tmpctx, &tl, TCOV_LEAF_DELAY), CV_TO_LOCAL_CB_DELAY);
	check("to_local cb revoke",
	      tap_tree2_control_block(tmpctx, &tl, TCOV_LEAF_REVOKE), CV_TO_LOCAL_CB_REVOKE);
	credit_to_remote_tree(tmpctx, &provider_payment, CV_WINDOW, &cp,
			      amount_sat(CV_V0), &tr);
	check("to_remote spk", tap_tree2_scriptpubkey(tmpctx, &tr), CV_TO_REMOTE_SPK);
	check("to_remote provider leaf",
	      tr.leaf[CREDIT_REMOTE_LEAF_PROVIDER], CV_PROVIDER_LEAF);
	check("to_remote cb claim",
	      tap_tree2_control_block(tmpctx, &tr, CREDIT_REMOTE_LEAF_CLAIM),
	      CV_TO_REMOTE_CB_CLAIM);
	check("to_remote cb provider",
	      tap_tree2_control_block(tmpctx, &tr, CREDIT_REMOTE_LEAF_PROVIDER),
	      CV_TO_REMOTE_CB_PROVIDER);

	/* A note: good as signed, refused for another c, hash, channel or key. */
	assert(hex_decode(CV_NOTE_HASH, strlen(CV_NOTE_HASH), h.u.u8, 32));
	assert(hex_decode(CV_NOTE_SIG, strlen(CV_NOTE_SIG), sig, 64));
	assert(credit_note_check(&cp.dtag, &cp.credit_key, CV_NOTE_C, &h, sig));
	assert(!credit_note_check(&cp.dtag, &cp.credit_key, CV_NOTE_C + 1, &h, sig));
	assert(!credit_note_check(&cp.dtag, &provider_funding, CV_NOTE_C, &h, sig));
	{
		struct sha256 other_tag = cp.dtag, other_hash = h;
		other_tag.u.u8[0] ^= 1;
		other_hash.u.u8[31] ^= 1;
		assert(!credit_note_check(&other_tag, &cp.credit_key, CV_NOTE_C, &h, sig));
		assert(!credit_note_check(&cp.dtag, &cp.credit_key, CV_NOTE_C, &other_hash, sig));
	}

	common_shutdown();
	return 0;
}
